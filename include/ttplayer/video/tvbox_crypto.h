// 覆盖 TVBox / 影视仓生态里最常见的「2423 前缀自解密」格式：
//
//   响应体 = hex( "$#" + key(13 字节, 每次随机) + "#$" + AES-CBC 密文 + iv(13 字节) )
//
//   hex 文本以 "2423" 开头（ASCII "$#" 的 hex）。规则来自 TVBox 安卓端
//   ApiConfig / AES.CBC()：
//     - key 取 "$#" 与 "#$" 之间的字节，右补 ASCII '0' 到 16 字节
//     - iv  取整体尾部 13 字节，右补 ASCII '0' 到 16 字节
//     - 密文为两者之间的全部字节，长度必为 16 的整数倍
//     - 算法 AES-128-CBC，明文为 JSON（可能带 PKCS#7 填充或尾部随机字节）
//
// 这里**不做** PKCS#7 去填充：实测部分源（肥猫）尾部并非标准填充，去填充会
// 抛错；JSON 对象配平截断（见 video_config.cpp）会自然丢弃尾部多余字节。
// 自己实现逆密码而非用 WinCrypt，正是为了完全控制这一行为且无需链接新库。

