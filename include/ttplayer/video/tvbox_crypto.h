inline std::uint8_t XTime(std::uint8_t x) {
    return static_cast<std::uint8_t>((x << 1) ^ ((x >> 7) * 0x1b));
}
inline std::uint8_t GMul(std::uint8_t a, std::uint8_t b) {
    std::uint8_t r = 0;
    while (b) {
        if (b & 1) r ^= a;
        a = XTime(a);
        b >>= 1;
    }
    return r;
}

inline void KeyExpansion(const std::uint8_t key[16], std::uint8_t w[176]) {
    std::memcpy(w, key, 16);
    std::uint8_t rcon = 0x01;
    for (int i = 4; i < 44; ++i) {
        std::uint8_t t[4] = {w[4 * (i - 1)], w[4 * (i - 1) + 1],
                             w[4 * (i - 1) + 2], w[4 * (i - 1) + 3]};
        if (i % 4 == 0) {
            const std::uint8_t tmp = t[0];
            t[0] = t[1]; t[1] = t[2]; t[2] = t[3]; t[3] = tmp;
            for (int k = 0; k < 4; ++k) t[k] = kSBox[t[k]];
            t[0] ^= rcon;
            rcon = XTime(rcon);
        }
        for (int k = 0; k < 4; ++k)
            w[4 * i + k] = static_cast<std::uint8_t>(w[4 * (i - 4) + k] ^ t[k]);
    }
}

inline void AddRoundKey(std::uint8_t s[16], const std::uint8_t* rk) {
    for (int i = 0; i < 16; ++i) s[i] ^= rk[i];
}
inline void InvSubBytes(std::uint8_t s[16]) {
    for (int i = 0; i < 16; ++i) s[i] = kInvSBox[s[i]];
}
inline void InvShiftRows(std::uint8_t s[16]) {
    std::uint8_t t = s[13];
    s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3];
    s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}
inline void InvMixColumns(std::uint8_t s[16]) {
    for (int c = 0; c < 4; ++c) {
        const std::uint8_t a0 = s[4 * c], a1 = s[4 * c + 1],
                           a2 = s[4 * c + 2], a3 = s[4 * c + 3];
        s[4 * c]     = GMul(a0,14) ^ GMul(a1,11) ^ GMul(a2,13) ^ GMul(a3, 9);
        s[4 * c + 1] = GMul(a0, 9) ^ GMul(a1,14) ^ GMul(a2,11) ^ GMul(a3,13);
        s[4 * c + 2] = GMul(a0,13) ^ GMul(a1, 9) ^ GMul(a2,14) ^ GMul(a3,11);
        s[4 * c + 3] = GMul(a0,11) ^ GMul(a1,13) ^ GMul(a2, 9) ^ GMul(a3,14);
    }
}
inline void InvCipher(const std::uint8_t in[16], std::uint8_t out[16],
                      const std::uint8_t w[176]) {
    std::uint8_t s[16];
    std::memcpy(s, in, 16);
    AddRoundKey(s, w + 160);
    for (int round = 9; round >= 1; --round) {
        InvShiftRows(s);
        InvSubBytes(s);
        AddRoundKey(s, w + 16 * round);
        InvMixColumns(s);
    }
    InvShiftRows(s);
    InvSubBytes(s);
    AddRoundKey(s, w);
    std::memcpy(out, s, 16);
}

// CBC 解密；cipher 长度必须是 16 的倍数。不做去填充。
inline bool Aes128CbcDecrypt(const std::uint8_t* cipher, std::size_t len,
                             const std::uint8_t key[16], const std::uint8_t iv[16],
                             std::string& out) {
    if (len == 0 || (len % 16) != 0) return false;
    std::uint8_t w[176];
    KeyExpansion(key, w);
    out.resize(len);
    std::uint8_t prev[16];
    std::memcpy(prev, iv, 16);
    for (std::size_t off = 0; off < len; off += 16) {
        std::uint8_t block[16], dec[16];
        std::memcpy(block, cipher + off, 16);
        InvCipher(block, dec, w);
        for (int i = 0; i < 16; ++i)
            out[off + i] = static_cast<char>(dec[i] ^ prev[i]);
        std::memcpy(prev, block, 16);
    }
    return true;
}

inline int HexVal(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}
inline bool HexDecode(std::string_view s, std::string& out) {
    if (s.size() % 2) return false;
    out.clear();
    out.reserve(s.size() / 2);
    for (std::size_t i = 0; i < s.size(); i += 2) {
        const int hi = HexVal(s[i]), lo = HexVal(s[i + 1]);
        if (hi < 0 || lo < 0) return false;
        out.push_back(static_cast<char>((hi << 4) | lo));
    }
    return true;
}
inline void RightPadZero(std::string& s, std::size_t n) {
    if (s.size() < n) s.append(n - s.size(), '0');
    else if (s.size() > n) s.resize(n);
}

// 嗅探并解密「2423」AES-CBC 自解密配置。成功时 out 为明文（可能是 JSON）。
// 返回 false 表示不是这个格式或解不出有效内容，调用方应继续尝试其它规则。
inline bool TryDecryptAesCbcSelf(std::string_view text, std::string& out) {
    // 去掉首尾空白，但不要改动中间的字节
    while (!text.empty() && (text.front() == ' ' || text.front() == '\r' ||
                             text.front() == '\n' || text.front() == '\t'))
        text.remove_prefix(1);
    while (!text.empty() && (text.back() == ' ' || text.back() == '\r' ||
                             text.back() == '\n' || text.back() == '\t'))
        text.remove_suffix(1);
    if (text.size() < 128 || text.substr(0, 4) != "2423") return false;

    std::string bin;
    if (!HexDecode(text, bin)) return false;
    if (bin.size() < 4 || bin[0] != '$' || bin[1] != '#') return false;
    const std::size_t p = bin.find("#$", 2);
    if (p == std::string::npos || p < 3) return false;

    std::string key = bin.substr(2, p - 2);
    const std::string body = bin.substr(p + 2);
    constexpr std::size_t kIvLen = 13;
    if (body.size() < kIvLen + 16) return false;
    std::string iv = body.substr(body.size() - kIvLen);
    const std::string cipher = body.substr(0, body.size() - kIvLen);
    if ((cipher.size() % 16) != 0) return false;
    RightPadZero(key, 16);
    RightPadZero(iv, 16);

    std::string plain;
    if (!Aes128CbcDecrypt(
            reinterpret_cast<const std::uint8_t*>(cipher.data()), cipher.size(),
            reinterpret_cast<const std::uint8_t*>(key.data()),
            reinterpret_cast<const std::uint8_t*>(iv.data()), plain))
        return false;
    // 明文中至少要能找到 JSON 起始花括号，否则视为密钥/格式不匹配。
    if (plain.find('{') == std::string::npos) return false;
    out = std::move(plain);
    return true;
}

